# Author the .blend test fixtures, and export each one with Blender's own glTF exporter.
#
#   npm run blend:fixtures
#
# Each scene below is saved as scripts/fixtures/blend/<name>.blend and exported beside it as
# <name>.glb with the settings export_gltf.py gives the baker. The tests read both: the direct
# reader on the .blend, and the glTF reader on Blender's export, and the two must agree.
#
# **That pairing is the point of committing a binary fixture.** The expectation is produced by a
# separate implementation — Blender evaluating its own file — so the test is not a transcription
# of the reader checked against itself. Every scene is built from numbers written here, so a
# fixture can be regenerated by anyone with Blender and compared byte for byte in what it means.
#
# Licence: Apache-2.0, as the rest of this repository. The files it writes are data authored here.

import math
