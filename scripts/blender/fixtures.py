def fresh():
    bpy.ops.wm.read_factory_settings(use_empty=True)


def link(obj, collection=None):
    (collection or bpy.context.scene.collection).objects.link(obj)
    return obj


def mesh_object(name, verts, faces, smooth=False, collection=None):
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    mesh.update()
    for poly in mesh.polygons:
        poly.use_smooth = smooth
    return link(bpy.data.objects.new(name, mesh), collection)


def material(name, color=(0.8, 0.8, 0.8, 1.0), metallic=0.0, roughness=0.5):
    mat = bpy.data.materials.new(name)
    if mat.node_tree is None:
        mat.use_nodes = True
    bsdf = principled(mat)
    bsdf.inputs['Base Color'].default_value = color
    bsdf.inputs['Metallic'].default_value = metallic
    bsdf.inputs['Roughness'].default_value = roughness
    return mat


def principled(mat):
    for node in mat.node_tree.nodes:
        if node.type == 'BSDF_PRINCIPLED':
            return node
    raise RuntimeError('no Principled BSDF in ' + mat.name)


def cube_data(size=1.0):
    s = size
    verts = [(-s, -s, -s), (s, -s, -s), (s, s, -s), (-s, s, -s),
             (-s, -s, s), (s, -s, s), (s, s, s), (-s, s, s)]
    faces = [(0, 3, 2, 1), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]
    return verts, faces


def uv_sphere(name, segments=16, rings=8, radius=1.0):
    mesh = bpy.data.meshes.new(name)
    bm = bmesh.new()
    bmesh.ops.create_uvsphere(bm, u_segments=segments, v_segments=rings, radius=radius,
                              calc_uvs=True)
    bm.to_mesh(mesh)
    bm.free()
    return link(bpy.data.objects.new(name, mesh))


def image(name, size, pixel, non_color=False):
    img = bpy.data.images.new(name, size, size, alpha=True)
    data = []
    for y in range(size):
        for x in range(size):
            data.extend(pixel(x, y))
    img.pixels = data
    img.file_format = 'PNG'
    img.pack()
    if non_color:
        img.colorspace_settings.name = 'Non-Color'
    return img


def save_blend(blend):
    # No `.blend1` beside it: a fixture is regenerated over itself, and Blender keeps the last copy.
    bpy.context.preferences.filepaths.save_version = 0
    bpy.ops.wm.save_as_mainfile(filepath=blend, compress=True)


def save(directory, name):
    blend = os.path.join(directory, name + '.blend')
    save_blend(blend)
    export(os.path.join(directory, name + '.glb'))
    print('fixture: ' + name)


